function getMobileNo(message: string, existMobile = "") {
  if (existMobile) {
    message = message.replaceAll(existMobile, "");
  }
  let mobile_no: any;
  let testMobile = [];
  let result: string = "";
  let langKeys = Object.keys(langMobileRegex);
  for (let i = 0; i < langKeys.length; i += 1) {
    for (let j = 0; j < langMobileRegex[langKeys[i]].length; j += 1) {
      mobile_no = message.match(langMobileRegex[langKeys[i]][j]);
      if (mobile_no) {
        break;
      }
    }

    if (mobile_no) {
      result = removeWhiteSpace(mobile_no[0]);
      testMobile.push({
        before: detectAndConvertMobile(mobile_no[0]),
        after: detectAndConvertMobile(result),
      });
    }
  }
  for (let i = 0; i < testMobile.length; i++) {
    if ((testMobile[i]["after"] + "").length > 10) {
      testMobile[i]["after"] = (testMobile[i]["after"] + "").substring(
        (testMobile[i]["after"] + "").length - 10
      );
      testMobile[i]["after"] = detectAndConvertMobile(testMobile[i]["after"]);
      return testMobile[i];
    }
  }

  if (testMobile.length) {
    return testMobile[0];
  }
  return { before: "", after: "" };
}

function removeWhiteSpace(mobileNo: string) {
  const extraChar = [" ", "-", "_", ">", "<"];
  for (let i = 0; i <= extraChar.length; i++) {
    while (mobileNo.includes(extraChar[i])) {
      mobileNo = mobileNo.replace(extraChar[i], "");
    }
  }
  return mobileNo;
}

